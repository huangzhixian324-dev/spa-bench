def impresa_pairs_from_source():
    src = (REPO / "workflows" / "methods" / "base_method.py").read_text(
        encoding="utf-8")
    block = re.search(r"PAIRS = \[(.*?)\]", src, re.S).group(1)
    pairs = re.findall(r'\("([A-Za-z0-9]+)",\s*"([A-Za-z0-9]+)"\)', block)
    return pairs


