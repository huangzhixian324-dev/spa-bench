def bh_within_cohort():
    # Standard Benjamini-Hochberg adjusted p-values: sort p ascending,
    # then q_i = min(1, min_{k>=i} p_k * m / k)  (cummin from the largest
    # rank downwards). 2026-09-07 fix: the previous implementation used
    # cummax from the smallest rank, which overestimates q for large p.
    qv = {}
    for cname in COHORTS:
        cells = sorted(((m, PM[cname][m]["p"]) for m in PM[cname]),
                       key=lambda t: t[1])
        m = len(cells)
        prev = 1.0
        for rank in range(m, 0, -1):
            mth, p = cells[rank - 1]
            prev = min(prev, p * m / rank, 1.0)
            qv[(cname, mth)] = prev
    return qv


